@Composable
fun StatusBadge(
    status: RequestStatus,
    syncState: SyncState = SyncState.SUBMITTED_TO_SERVER,
    modifier: Modifier = Modifier
) {
    if (syncState == SyncState.QUEUED_LOCALLY) {
        Surface(
            modifier = modifier,
            shape = RoundedCornerShape(12.dp),
            color = StatusPending.copy(alpha = 0.2f)
        ) {
            Row(
                modifier = Modifier.padding(horizontal = 10.dp, vertical = 4.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                Icon(
                    imageVector = Icons.Default.Sync,
                    contentDescription = null,
                    modifier = Modifier.size(12.dp),
                    tint = StatusPending
                )
                Spacer(modifier = Modifier.width(4.dp))
                Text(
                    text = "Syncing...",
                    style = MaterialTheme.typography.labelMedium.copy(fontWeight = FontWeight.Bold),
                    color = StatusPending
                )
            }
        }
    } else if (syncState == SyncState.SYNC_FAILED) {
        Surface(
            modifier = modifier,
            shape = RoundedCornerShape(12.dp),
            color = MaterialTheme.colorScheme.errorContainer
        ) {
            Text(
                text = "Sync Failed",
                modifier = Modifier.padding(horizontal = 10.dp, vertical = 4.dp),
                style = MaterialTheme.typography.labelMedium.copy(fontWeight = FontWeight.Bold),
                color = MaterialTheme.colorScheme.onErrorContainer
            )
        }
    } else {
        val (bgColor, label) = when (status) {
            RequestStatus.PENDING -> StatusPending to "Pending"
            RequestStatus.ACCEPTED -> StatusAccepted to "Accepted"
            RequestStatus.IN_PROGRESS -> StatusInProgress to "In Progress"
            RequestStatus.COMPLETED -> StatusCompleted to "Completed"
            RequestStatus.CANCELLED -> StatusCancelled to "Cancelled"
            RequestStatus.REJECTED -> StatusRejected to "Rejected"
        }

        Surface(
            modifier = modifier,
            shape = RoundedCornerShape(12.dp),
            color = bgColor.copy(alpha = 0.15f)
        ) {
            Text(
                text = label,
                modifier = Modifier.padding(horizontal = 10.dp, vertical = 4.dp),
                style = MaterialTheme.typography.labelMedium.copy(fontWeight = FontWeight.Bold),
                color = bgColor
            )
        }
    }
}

@Composable
fun CompanyCard(
    company: Company,
    onClick: () -> Unit,
    modifier: Modifier = Modifier
) {
    Card(
        modifier = modifier
            .fillMaxWidth()
            .clickable(onClick = onClick),
        shape = RoundedCornerShape(16.dp),
        elevation = CardDefaults.cardElevation(defaultElevation = 2.dp),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)
    ) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(16.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Box(
                modifier = Modifier
                    .size(64.dp)
                    .clip(RoundedCornerShape(12.dp))
                    .background(MaterialTheme.colorScheme.primaryContainer),
                contentAlignment = Alignment.Center
            ) {
                if (!company.logoUrl.isNullOrEmpty()) {
                    AsyncImage(
                        model = company.logoUrl,
                        contentDescription = company.name,
                        contentScale = ContentScale.Crop,
                        modifier = Modifier.fillMaxSize()
                    )
                } else {
                    Icon(
                        imageVector = Icons.Default.Business,
                        contentDescription = null,
                        tint = MaterialTheme.colorScheme.onPrimaryContainer,
                        modifier = Modifier.size(32.dp)
                    )
                }
            }

            Spacer(modifier = Modifier.width(16.dp))

            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = company.name,
                    style = MaterialTheme.typography.titleMedium.copy(fontWeight = FontWeight.Bold),
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis
                )
                Spacer(modifier = Modifier.height(4.dp))
                Text(
                    text = company.description,
                    style = MaterialTheme.typography.bodyMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    maxLines = 2,
                    overflow = TextOverflow.Ellipsis
                )
                Spacer(modifier = Modifier.height(6.dp))
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Icon(
                        imageVector = Icons.Default.LocationOn,
                        contentDescription = null,
                        modifier = Modifier.size(14.dp),
                        tint = MaterialTheme.colorScheme.primary
                    )
                    Spacer(modifier = Modifier.width(4.dp))
                    Text(
                        text = company.location.ifEmpty { "Location not specified" },
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
            }
        }
    }
}

